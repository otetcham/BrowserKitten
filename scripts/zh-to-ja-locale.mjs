function applyRules(text) {
  let s = String(text ?? '');
  for (const [from, to] of RULES) {
    if (s.includes(from)) s = s.split(from).join(to);
  }
  return s;
}

function walk(val) {
  if (Array.isArray(val)) return val.map((line) => applyRules(line));
  if (typeof val === 'string') return applyRules(val);
  return val;
}

